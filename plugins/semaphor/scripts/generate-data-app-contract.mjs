#!/usr/bin/env node
import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import process from 'node:process';
import {
  assertValidCodegenSummary,
} from './data-app-codegen-summary-validation.mjs';

const DEFAULT_OUTPUT_DIR = 'src/semaphor/generated';
const GENERATED_CONTRACT_SCHEMA_VERSION = 'semaphor-generated-data-app-contract/v1';
const CONTRACT_MANIFEST_SCHEMA_VERSION = 'semaphor-generated-data-app-contract-manifest/v1';
const GENERATED_HEADER = `// Generated by Semaphor Agent Plugin. Do not hand-edit analytics wiring here.
// Regenerate from the accepted semaphor_plan_data_app codegenSummary when the plan changes.
`;

const args = parseArgs(process.argv.slice(2));

try {
  const workspaceDir = path.resolve(firstString(args.dir, args.workspaceDir, process.cwd()));
  const outputDir = path.resolve(workspaceDir, firstString(args.output, args.outputDir, DEFAULT_OUTPUT_DIR));
  assertInsideDirectory({
    parentDir: workspaceDir,
    childPath: outputDir,
    label: 'outputDir',
  });
  const artifact = readPlanArtifact({ args, workspaceDir });
  const summary = normalizeCodegenSummary(artifact);
  const contract = buildContract(summary);
  if (
    contract.views.length === 0 &&
    !booleanArg(args.allowEmpty) &&
    !booleanArg(args['allow-empty']) &&
    !booleanArg(args.allowEmptyContract)
  ) {
    throw new Error(
      'Contract generation produced zero executable views. Stop and ask for a different domain/goal or semantic model improvement; pass --allow-empty only for an explicit model-gap report.',
    );
  }
  const files = renderFiles(contract);
  const manifest = buildContractManifest({ contract, files });
  files['contract.manifest.json'] = `${JSON.stringify(manifest, null, 2)}\n`;

  fs.mkdirSync(outputDir, { recursive: true });
  for (const [fileName, content] of Object.entries(files)) {
    fs.writeFileSync(path.join(outputDir, fileName), content, 'utf8');
  }

  const generatedFiles = Object.keys(files).map((fileName) =>
    path.relative(workspaceDir, path.join(outputDir, fileName)),
  );
  const result = {
    ok: true,
    workspaceDir,
    outputDir: path.relative(workspaceDir, outputDir),
    schemaVersion: GENERATED_CONTRACT_SCHEMA_VERSION,
    manifestPath: path.relative(workspaceDir, path.join(outputDir, 'contract.manifest.json')),
    contentHash: manifest.generatedContentHash,
    generatedFiles,
    inputCount: contract.inputs.length,
    executableViewCount: contract.views.length,
    presentationViewCount: contract.presentationViews.length,
    queryCount: contract.views.length,
    optionQueryCount: contract.optionQueries.length,
    validationCommand:
      'semaphor_validate_data_app_contract(runBuild=true, strict=false)',
    usageExample: renderUsageExample(contract),
    warnings: contract.warnings,
  };
  writeResult(result);
} catch (error) {
  const message = error instanceof Error ? error.message : String(error);
  writeResult({ ok: false, error: message });
  process.exit(1);
}

function parseArgs(argv) {
  const parsed = {};
  for (let index = 0; index < argv.length; index += 1) {
    const token = argv[index];
    if (!token.startsWith('--')) {
      continue;
    }
    const key = token.slice(2);
    if (key === 'stdin' || key === 'json') {
      parsed[key] = true;
      continue;
    }
    const value = argv[index + 1];
    if (value === undefined || value.startsWith('--')) {
      parsed[key] = true;
      continue;
    }
    parsed[key] = value;
    index += 1;
  }
  return parsed;
}

function readPlanArtifact({ args, workspaceDir }) {
  if (args.stdin) {
    const input = fs.readFileSync(0, 'utf8');
    if (!input.trim()) {
      throw new Error('No JSON was provided on stdin.');
    }
    return JSON.parse(input);
  }

  const planPath = firstString(args.plan, args.planArtifactPath, args.codegenSummaryPath);
  if (!planPath) {
    throw new Error(
      'Pass --plan <path> with a codegenSummary/plan artifact. --stdin is only a manual CLI fallback.',
    );
  }

  const resolvedPlanPath = path.resolve(workspaceDir, planPath);
  return JSON.parse(fs.readFileSync(resolvedPlanPath, 'utf8'));
}

function assertInsideDirectory({ parentDir, childPath, label }) {
  const relative = path.relative(parentDir, childPath);
  if (
    relative === '' ||
    (!relative.startsWith('..') && !path.isAbsolute(relative))
  ) {
    return;
  }
  throw new Error(`${label} must resolve inside workspaceDir.`);
}

function normalizeCodegenSummary(artifact) {
  const summary = artifact;
  assertValidCodegenSummary(summary);
  return summary;
}

function buildContract(summary) {
  const warnings = [];
  const sources = uniqueBy(
    summary.sources.map((source) => ({
      raw: source,
      key: source.sourceKey || sourceKey(source),
      name: '',
    })),
    (source) => source.key,
  );
  assignUniqueNames(sources, (source) =>
    camelCase(
      source.raw.label ||
        source.raw.datasetName ||
        source.raw.datasetId ||
        source.raw.name ||
        source.raw.kind ||
        'source',
    ),
  );

  const sourceNameByKey = new Map(sources.map((source) => [source.key, source.name]));
  const fieldItems = [];
  for (const input of summary.inputs) {
    collectField(fieldItems, input.fieldRef);
    for (const binding of input.bindings || []) {
      collectField(fieldItems, binding.fieldRef);
    }
    collectField(fieldItems, input.optionQuery?.valueFieldRef);
    collectField(fieldItems, input.optionQuery?.labelFieldRef);
    collectField(fieldItems, input.optionQuery?.filterFieldRef);
  }
  for (const filterContract of summary.filterContracts) {
    collectField(fieldItems, filterContract.fieldRef);
    collectField(fieldItems, filterContract.optionQuery?.valueFieldRef);
    collectField(fieldItems, filterContract.optionQuery?.labelFieldRef);
    collectField(fieldItems, filterContract.optionQuery?.filterFieldRef);
    for (const binding of filterContract.bindings || []) {
      collectField(fieldItems, binding.fieldRef);
    }
  }
  for (const view of summary.views) {
    for (const field of view.fields || []) {
      collectField(fieldItems, field);
    }
    collectFieldsFromValue(fieldItems, view.sdkSpec?.spec);
  }
  const checklist = summary.implementationChecklist || {};
  for (const bindings of Object.values(checklist.bindingsByView || {})) {
    for (const binding of Array.isArray(bindings) ? bindings : []) {
      collectField(fieldItems, binding.fieldRef);
      collectField(fieldItems, binding.optionValueField);
      collectField(fieldItems, binding.optionLabelField);
    }
  }
  for (const option of checklist.requiredInputOptions || []) {
    collectField(fieldItems, option.visibleLabelField);
    collectField(fieldItems, option.optionValueField);
    collectField(fieldItems, option.runtimeFilterField);
  }

  const fields = uniqueBy(
    fieldItems
      .filter((field) => field?.name)
      .map((field) => ({
        raw: field,
        key: fieldKey(field),
        name: '',
      })),
    (field) => field.key,
  );
  assignUniqueNames(fields, (field) =>
    camelCase([
      field.raw.sourceKey ? shortSourceName(field.raw.sourceKey) : '',
      field.raw.aggregate ? field.raw.aggregate.toLowerCase() : '',
      field.raw.name,
    ].filter(Boolean).join('_')),
  );
  const fieldNameByKey = new Map(fields.map((field) => [field.key, field.name]));

  const inputs = summary.inputs.map((input) => ({
    raw: input,
    name: camelCase(input.id || input.label || 'input'),
  }));
  assignUniqueNames(inputs, (input) => input.name);

  const optionQueries = inputs
    .filter((input) => input.raw.optionQuery)
    .map((input) => ({
      input,
      name: `${input.name}Options`,
      raw: input.raw.optionQuery,
    }));
  assignUniqueNames(optionQueries, (query) => query.name);

  for (const query of optionQueries) {
    if (
      fieldRefsReferToSameField(query.raw.labelFieldRef, query.raw.valueFieldRef) &&
      isIdentifierFieldRef(query.raw.valueFieldRef)
    ) {
      warnings.push(
        `Input option query ${query.raw.spec?.inputId || query.input.raw.id || query.name} uses identifier field ${query.raw.valueFieldRef.name} as both label and value. It can execute, but the UI will show key values unless the semantic model exposes a human-readable label through a modeled relationship.`,
      );
    }
  }

  const views = summary.views
    .filter((view) => view.sdkSpec?.builder && view.sdkSpec?.spec)
    .map((view) => ({
      raw: view,
      name: camelCase(view.id || view.title || 'query'),
    }));
  assignUniqueNames(views, (view) => view.name);

  const presentationViews = summary.views
    .filter((view) => isPresentationView(view) && !view.sdkSpec?.spec)
    .map((view) => compactPresentationView(view));

  for (const view of summary.views) {
    if (
      (!view.sdkSpec?.builder || !view.sdkSpec?.spec) &&
      !isPresentationView(view)
    ) {
      warnings.push(`Skipped view ${view.id || view.title || 'unknown'} because it has no sdkSpec.`);
    }
  }
  validateFilterContractScopes({
    inputs,
    views,
    filterContracts: summary.filterContracts,
  });

  return {
    summary,
    title: summary.title || 'Semaphor Data App',
    sources,
    fields,
    inputs,
    optionQueries,
    views,
    presentationViews,
    filterContracts: summary.filterContracts,
    checklist,
    sourceNameByKey,
    fieldNameByKey,
    warnings,
  };
}

function validateFilterContractScopes({ inputs, views, filterContracts }) {
  const inputIds = new Set(inputs.map((input) => input.raw.id).filter(Boolean));
  const executableViewIds = new Set(views.map((view) => view.raw.id).filter(Boolean));
  for (const [index, filterContract] of filterContracts.entries()) {
    if (!inputIds.has(filterContract.inputId)) {
      throw new Error(`filterContracts.${index}.inputId must reference a generated input.`);
    }
    const appliesToViewIds = new Set(filterContract.appliesToViewIds || []);
    const notAppliedToViewIds = new Set(filterContract.notAppliedToViewIds || []);
    for (const [viewIndex, viewId] of (filterContract.appliesToViewIds || []).entries()) {
      if (!executableViewIds.has(viewId)) {
        throw new Error(
          `filterContracts.${index}.appliesToViewIds.${viewIndex} must reference an executable generated view.`,
        );
      }
    }
    for (const [viewIndex, viewId] of (filterContract.notAppliedToViewIds || []).entries()) {
      if (!executableViewIds.has(viewId)) {
        throw new Error(
          `filterContracts.${index}.notAppliedToViewIds.${viewIndex} must reference an executable generated view.`,
        );
      }
    }
    for (const [bindingIndex, binding] of (filterContract.bindings || []).entries()) {
      if (!executableViewIds.has(binding.viewId)) {
        throw new Error(
          `filterContracts.${index}.bindings.${bindingIndex}.viewId must reference an executable generated view.`,
        );
      }
      if (!appliesToViewIds.has(binding.viewId)) {
        throw new Error(
          `filterContracts.${index}.bindings.${bindingIndex}.viewId must be included in appliesToViewIds.`,
        );
      }
      if (notAppliedToViewIds.has(binding.viewId)) {
        throw new Error(
          `filterContracts.${index}.bindings.${bindingIndex}.viewId must not be listed in notAppliedToViewIds.`,
        );
      }
    }
  }
}

function renderFiles(contract) {
  return {
    'sources.ts': renderSources(contract),
    'fields.ts': renderFields(contract),
    'inputs.ts': renderInputs(contract),
    'queries.ts': renderQueries(contract),
    'bindings.ts': renderBindings(contract),
    'accessors.ts': renderAccessors(contract),
    'metadata.ts': renderMetadata(contract),
    'index.ts': renderIndex(),
  };
}

function buildContractManifest({ contract, files }) {
  return {
    schemaVersion: CONTRACT_MANIFEST_SCHEMA_VERSION,
    generatedContractSchemaVersion: GENERATED_CONTRACT_SCHEMA_VERSION,
    generator: {
      name: 'semaphor-agent-plugin',
      version: readPluginPackageVersion(),
    },
    generatedContentHash: hashGeneratedFiles(files),
    codegenSummaryHash: hashCanonicalJson(contract.summary),
    codegenSummary: contract.summary,
  };
}

function hashGeneratedFiles(files) {
  const hash = crypto.createHash('sha256');
  for (const fileName of Object.keys(files).sort()) {
    hash.update(fileName);
    hash.update('\0');
    hash.update(files[fileName]);
    hash.update('\0');
  }
  return `sha256:${hash.digest('hex')}`;
}

function hashCanonicalJson(value) {
  return `sha256:${crypto.createHash('sha256').update(canonicalJson(value)).digest('hex')}`;
}

function canonicalJson(value) {
  if (value === null || typeof value !== 'object') {
    return JSON.stringify(value);
  }
  if (Array.isArray(value)) {
    return `[${value.map((item) => canonicalJson(item)).join(',')}]`;
  }
  const entries = Object.keys(value)
    .sort()
    .filter((key) => value[key] !== undefined)
    .map((key) => `${JSON.stringify(key)}:${canonicalJson(value[key])}`);
  return `{${entries.join(',')}}`;
}

function readPluginPackageVersion() {
  try {
    const packagePath = path.resolve(path.dirname(process.argv[1]), '..', 'package.json');
    const pkg = JSON.parse(fs.readFileSync(packagePath, 'utf8'));
    return typeof pkg.version === 'string' ? pkg.version : 'unknown';
  } catch {
    return 'unknown';
  }
}

function renderUsageExample(contract) {
  const rowView = contract.views.find((view) => isRowShapedBuilder(view.raw.sdkSpec?.builder));
  if (rowView) {
    return [
      'import { appInputSpecs, createInputHandleMap, queries, queryOptionsForView, rowValuesForView, semaphorGeneratedContractMetadata } from "./semaphor/generated";',
      'const handles = useSemaphorInputs(appInputSpecs);',
      'const inputHandles = createInputHandleMap(handles);',
      `const result = useSemaphorQuery(queries.${rowView.name}, queryOptionsForView.${rowView.name}(inputHandles));`,
      `const rows = result.records.map((row) => rowValuesForView.${rowView.name}(row, result.columns));`,
      'const presentationViews = semaphorGeneratedContractMetadata.presentationViews;',
    ].join('\n');
  }
  const firstView = contract.views[0];
  const queryLine = firstView
    ? `const result = useSemaphorQuery(queries.${firstView.name}, queryOptionsForView.${firstView.name}(inputHandles));`
    : 'const result = undefined;';
  return [
    'import { appInputSpecs, createInputHandleMap, queries, queryOptionsForView, semaphorGeneratedContractMetadata } from "./semaphor/generated";',
    'const handles = useSemaphorInputs(appInputSpecs);',
    'const inputHandles = createInputHandleMap(handles);',
    queryLine,
    'const presentationViews = semaphorGeneratedContractMetadata.presentationViews;',
  ].join('\n');
}

function renderSources(contract) {
  const body = contract.sources.map(({ name, raw }) => {
    const value = renderSourceValue(raw, contract);
    return `  ${name}: ${value},`;
  }).join('\n');
  return `${GENERATED_HEADER}
import { semaphor } from "react-semaphor/data-app-sdk";

export const sources = {
${body}
} as const;
`;
}

function renderSourceValue(source) {
  if (source.kind === 'semantic') {
    const spec = {
      domainId: source.domainId,
      datasetId: source.datasetId,
      datasetName: source.datasetName,
      label: source.label,
    };
    return `semaphor.source.semantic(${renderPlainObject(removeUndefined(spec))})`;
  }
  return `${renderPlainObject(removeUndefined({ ...source, sourceKey: undefined }))} as const`;
}

function renderFields(contract) {
  const body = contract.fields.map(({ name, raw }) => {
    const value = renderFieldValue(raw, contract);
    return `  ${name}: ${value},`;
  }).join('\n');
  return `${GENERATED_HEADER}
import { sources } from "./sources";

export const fields = {
${body}
} as const;
`;
}

function renderFieldValue(field, contract) {
  const rendered = {
    name: field.name,
    label: field.label,
    role: field.role,
    dataType: field.dataType,
    aggregate: field.aggregate,
  };
  const sourceName = field.sourceKey ? contract.sourceNameByKey.get(field.sourceKey) : undefined;
  const entries = Object.entries(removeUndefined(rendered))
    .map(([key, value]) => `${JSON.stringify(key)}: ${renderValue(value, contract)}`);
  if (sourceName) {
    entries.push(`"source": sources.${sourceName}`);
  }
  return `{ ${entries.join(', ')} }`;
}

function renderInputs(contract) {
  const filterSpecs = contract.inputs.map((input) => {
    const fieldName = fieldNameFor(input.raw.fieldRef, contract);
    const spec = [
      `id: ${JSON.stringify(input.raw.id)}`,
      `label: ${JSON.stringify(input.raw.label || input.raw.id)}`,
      `operator: ${JSON.stringify(operatorForInput(input.raw))}`,
    ];
    if (fieldName) {
      spec.push(`field: fields.${fieldName}`);
    }
    if (input.raw.relationshipHint) {
      spec.push(`relationshipHint: ${renderPlainObject(input.raw.relationshipHint)}`);
    }
    if (!fieldName) {
      throw new Error(`Input ${input.raw.id || input.name} is missing a generated field reference.`);
    }
    return `  ${input.name}: semaphor.filter({ ${spec.join(', ')} }),`;
  }).join('\n');

  const appSpecs = contract.inputs.map((input) => `filterSpecs.${input.name}`).join(', ');
  const inputIds = contract.inputs.map((input) => JSON.stringify(input.raw.id)).join(', ');
  const optionQueries = contract.optionQueries.map((query) => {
    const input = query.input.raw;
    const option = query.raw;
    const sourceName = sourceNameFor(option.sourceKey ? { sourceKey: option.sourceKey } : option.source, contract);
    const valueField = fieldNameFor(option.valueFieldRef, contract);
    const labelField = fieldNameFor(option.labelFieldRef, contract);
    const parts = [
      `id: ${JSON.stringify(option.id || `${input.id}-options`)}`,
      `inputId: ${JSON.stringify(input.id)}`,
    ];
    if (sourceName) parts.push(`source: sources.${sourceName}`);
    if (valueField) parts.push(`valueField: fields.${valueField}`);
    if (labelField) parts.push(`labelField: fields.${labelField}`);
    if (option.population) parts.push(`population: ${renderPlainObject(option.population)}`);
    if (option.dependencies) parts.push(`dependencies: ${renderPlainObject(option.dependencies)}`);
    parts.push(`limit: ${JSON.stringify(option.limit || option.spec?.limit || 100)}`);
    if (!sourceName || !valueField || !labelField) {
      throw new Error(`Input option query ${option.id || `${input.id}-options`} is missing source, valueField, or labelField.`);
    }
    return `  ${query.name}: semaphor.inputOptions({ ${parts.join(', ')} }),`;
  }).join('\n');

  return `${GENERATED_HEADER}
import { semaphor } from "react-semaphor/data-app-sdk";
import type { SemaphorInputHandle } from "react-semaphor/data-app-sdk";
import { fields } from "./fields";
import { sources } from "./sources";
import type { SemaphorGeneratedInputId } from "./metadata";

export const filterSpecs = {
${filterSpecs}
} as const;

export const appInputSpecs = [${appSpecs}] as const;
export const appInputIds = [${inputIds}] as const;

export type SemaphorGeneratedInputHandleMap = Partial<Record<SemaphorGeneratedInputId, SemaphorInputHandle>>;

export function createInputHandleMap(handles: readonly SemaphorInputHandle[]): SemaphorGeneratedInputHandleMap {
  return Object.fromEntries(appInputIds.map((id, index) => [id, handles[index]])) as SemaphorGeneratedInputHandleMap;
}

export const inputOptionQueries = {
${optionQueries}
} as const;
`;
}

function renderQueries(contract) {
  const queryEntries = contract.views.map((view) => {
    const builder = builderMethod(view.raw.sdkSpec.builder);
    const spec = sdkBuilderSpecForView(view);
    return `  ${view.name}: semaphor.${builder}(${renderValue(spec, contract)}),`;
  }).join('\n');
  return `${GENERATED_HEADER}
import { semaphor } from "react-semaphor/data-app-sdk";
import { fields } from "./fields";
import { sources } from "./sources";

export const queries = {
${queryEntries}
} as const;
`;
}

function sdkBuilderSpecForView(view) {
  const rawSpec = view.raw.sdkSpec?.spec || {};
  const { kind: _plannerOnlyKind, id: _ignoredId, ...builderSpec } = rawSpec;
  return {
    ...builderSpec,
    id: view.raw.id,
    label: view.raw.visualSpec?.title || view.raw.title || builderSpec.label,
  };
}

function renderBindings(contract) {
  const helpers = contract.views.map((view) => {
    const bindings = filterBindingsForView(contract, view.raw.id);
    const renderedBindings = bindings.map((binding) => {
      const inputId = binding.inputId;
      const fieldName = fieldNameFor(binding.fieldRef, contract);
      if (!inputId || !fieldName) {
        return '';
      }
      const bindingParts = [`field: fields.${fieldName}`];
      if (binding.relationshipHint) {
        bindingParts.push(`relationshipHint: ${renderPlainObject(binding.relationshipHint)}`);
      } else if (Array.isArray(binding.relationshipsUsed) && binding.relationshipsUsed.length > 0) {
        const relationshipIds = binding.relationshipsUsed
          .map((relationship) => relationship?.id)
          .filter((id) => typeof id === 'string' && id.length > 0);
        if (relationshipIds.length > 0) {
          bindingParts.push(`relationshipHint: ${renderPlainObject({ relationshipIds })}`);
        }
      }
      const handleRef = `inputHandles[${JSON.stringify(inputId)}]`;
      return `    if (${handleRef}) {
      inputs.push(semaphor.bindInput(${handleRef}, { ${bindingParts.join(', ')} }));
    }`;
    }).filter(Boolean).join('\n');
    return `  ${view.name}(inputHandles: SemaphorGeneratedInputHandleMap): SemaphorInputReference[] {
    const inputs: SemaphorInputReference[] = [];
${renderedBindings}
    return inputs;
  },`;
  }).join('\n\n');

  const optionHelpers = contract.views.map((view) => {
    return `  ${view.name}(inputHandles: SemaphorGeneratedInputHandleMap): SemaphorQueryRuntimeOptions {
    return {
      inputs: inputsForView.${view.name}(inputHandles),
      debug: queryDebugForView.${view.name},
    };
  },`;
  }).join('\n\n');

  const inputSwitchCases = contract.views.map((view) => (
    `    case ${JSON.stringify(view.raw.id)}:
      return inputsForView.${view.name}(inputHandles);`
  )).join('\n');
  const optionSwitchCases = contract.views.map((view) => (
    `    case ${JSON.stringify(view.raw.id)}:
      return queryOptionsForView.${view.name}(inputHandles);`
  )).join('\n');

  return `${GENERATED_HEADER}
import { semaphor } from "react-semaphor/data-app-sdk";
import type { SemaphorInputReference, SemaphorQueryRuntimeOptions } from "react-semaphor/data-app-sdk";
import { fields } from "./fields";
import type { SemaphorGeneratedInputHandleMap } from "./inputs";
import { queryDebugForView } from "./metadata";
import type { SemaphorGeneratedQueryViewId } from "./metadata";

export const inputsForView = {
${helpers}
} as const;

export const queryOptionsForView = {
${optionHelpers}
} as const;

export function inputsForViewId(
  viewId: SemaphorGeneratedQueryViewId,
  inputHandles: SemaphorGeneratedInputHandleMap,
): SemaphorInputReference[] {
  switch (viewId) {
${inputSwitchCases}
  }
  throw new Error(\`Unknown generated Semaphor view id: \${viewId}\`);
}

export function queryOptionsForViewId(
  viewId: SemaphorGeneratedQueryViewId,
  inputHandles: SemaphorGeneratedInputHandleMap,
): SemaphorQueryRuntimeOptions {
  switch (viewId) {
${optionSwitchCases}
  }
  throw new Error(\`Unknown generated Semaphor view id: \${viewId}\`);
}
`;
}

function filterBindingsForView(contract, viewId) {
  return contract.filterContracts.flatMap((filterContract) =>
    (filterContract.bindings || [])
      .filter((binding) => binding.viewId === viewId)
      .map((binding) => ({
        inputId: filterContract.inputId,
        fieldRef: binding.fieldRef,
        relationshipHint: binding.relationshipHint,
        relationshipsUsed: binding.relationshipsUsed,
      }))
  );
}

function renderAccessors(contract) {
  const fieldsForViewEntries = contract.views.map((view) => {
    const accessorFields = accessorFieldsForView(view, contract);
    const fieldEntries = accessorFields.map((field) => {
      const fieldName = fieldNameFor(field.raw, contract);
      if (!fieldName) return '';
      return `    ${field.name}: fields.${fieldName},`;
    }).filter(Boolean).join('\n');
    return `  ${view.name}: {
${fieldEntries}
  },`;
  }).join('\n');

  const columnKeyEntries = contract.views.map((view) => {
    const accessorFields = accessorFieldsForView(view, contract);
    const keyEntries = accessorFields.map((field) => (
      `      ${field.name}: resolveColumnKey(columns, fieldsForView.${view.name}.${field.name}),`
    )).join('\n');
    return `  ${view.name}(columns: SemaphorGeneratedColumns): Record<keyof typeof fieldsForView.${view.name}, string | undefined> {
    return {
${keyEntries}
    };
  },`;
  }).join('\n\n');

  const rowValueEntries = contract.views.map((view) => {
    const accessorFields = accessorFieldsForView(view, contract);
    const valueEntries = accessorFields.map((field) => (
      `      ${field.name}: readCell(row, columns, fieldsForView.${view.name}.${field.name}),`
    )).join('\n');
    return `  ${view.name}(row: SemaphorGeneratedRow, columns: SemaphorGeneratedColumns): Record<keyof typeof fieldsForView.${view.name}, unknown> {
    return {
${valueEntries}
    };
  },`;
  }).join('\n\n');

  return `${GENERATED_HEADER}
import type { SemaphorFieldRef, SemaphorResultColumn } from "react-semaphor/data-app-sdk";
import { fields } from "./fields";

export type SemaphorGeneratedRow = Record<string, unknown>;
export type SemaphorGeneratedColumns = readonly SemaphorResultColumn[] | null | undefined;

export const fieldsForView = {
${fieldsForViewEntries}
} as const;

export const columnKeysForView = {
${columnKeyEntries}
} as const;

export const rowValuesForView = {
${rowValueEntries}
} as const;

export function resolveColumnKey(
  columns: SemaphorGeneratedColumns,
  field: SemaphorFieldRef,
): string | undefined {
  return resolveColumn(columns, field)?.key;
}

export function readCell(
  row: SemaphorGeneratedRow,
  columns: SemaphorGeneratedColumns,
  field: SemaphorFieldRef,
): unknown {
  const key = resolveColumnKey(columns, field);
  return key ? row[key] : undefined;
}

export function readNumberCell(
  row: SemaphorGeneratedRow,
  columns: SemaphorGeneratedColumns,
  field: SemaphorFieldRef,
): number | null {
  const value = readCell(row, columns, field);
  if (typeof value === "number") {
    return Number.isFinite(value) ? value : null;
  }
  if (typeof value === "string" && value.trim().length > 0) {
    const parsed = Number(value);
    return Number.isFinite(parsed) ? parsed : null;
  }
  return null;
}

export function readStringCell(
  row: SemaphorGeneratedRow,
  columns: SemaphorGeneratedColumns,
  field: SemaphorFieldRef,
): string {
  const value = readCell(row, columns, field);
  return value === null || value === undefined ? "" : String(value);
}

function resolveColumn(
  columns: SemaphorGeneratedColumns,
  field: SemaphorFieldRef,
): SemaphorResultColumn | undefined {
  if (!columns || columns.length === 0) {
    return undefined;
  }
  return (
    findUniqueColumn(columns, (column) => column.name === field.name && columnMatchesField(column, field, true)) ||
    findUniqueColumn(columns, (column) => column.name === field.name && columnMatchesField(column, field, false)) ||
    findUniqueColumn(columns, (column) => column.label === field.label && columnMatchesField(column, field, true)) ||
    findUniqueColumn(columns, (column) => column.label === field.label && columnMatchesField(column, field, false))
  );
}

function findUniqueColumn(
  columns: readonly SemaphorResultColumn[],
  predicate: (column: SemaphorResultColumn) => boolean,
): SemaphorResultColumn | undefined {
  const matches = columns.filter(predicate);
  return matches.length === 1 ? matches[0] : undefined;
}

function columnMatchesField(
  column: SemaphorResultColumn,
  field: SemaphorFieldRef,
  requireComparableSource: boolean,
): boolean {
  if (field.aggregate && column.aggregate && field.aggregate !== column.aggregate) {
    return false;
  }
  if (!field.aggregate && column.aggregate) {
    return false;
  }
  if (requireComparableSource && !column.source) {
    return false;
  }
  return sourcesReferToSameDataset(column.source, field.source);
}

function sourcesReferToSameDataset(
  left: SemaphorFieldRef["source"] | undefined,
  right: SemaphorFieldRef["source"] | undefined,
): boolean {
  if (!left || !right) {
    return true;
  }
  if (left.kind !== right.kind) {
    return false;
  }
  if (left.kind === "physical" && right.kind === "physical") {
    if (left.connectionId && right.connectionId && left.connectionId !== right.connectionId) {
      return false;
    }
    if (left.databaseName && right.databaseName && left.databaseName !== right.databaseName) {
      return false;
    }
    if (left.schemaName && right.schemaName && left.schemaName !== right.schemaName) {
      return false;
    }
    if (left.tableName && right.tableName && left.tableName !== right.tableName) {
      return false;
    }
    return true;
  }
  if (left.kind === "sql" && right.kind === "sql") {
    return !left.connectionId || !right.connectionId || left.connectionId === right.connectionId;
  }
  if (left.kind === "semantic" && right.kind === "semantic") {
    if (left.domainId && right.domainId && left.domainId !== right.domainId) {
      return false;
    }
    if (left.datasetId && right.datasetId) {
      return left.datasetId === right.datasetId;
    }
    if (left.datasetName && right.datasetName) {
      return left.datasetName === right.datasetName;
    }
    return true;
  }
  return false;
}
`;
}

