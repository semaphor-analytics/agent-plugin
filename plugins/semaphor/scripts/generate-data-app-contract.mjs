function collectFieldsFromValue(fields, value) {
  if (!value || typeof value !== 'object') {
    return;
  }
  if (Array.isArray(value)) {
    for (const item of value) collectFieldsFromValue(fields, item);
    return;
  }
  if (looksLikeFieldRef(value)) {
    collectField(fields, compactField(value));
  }
  for (const item of Object.values(value)) {
    collectFieldsFromValue(fields, item);
  }
}

function accessorFieldsForView(view, contract) {
  const collected = [];
  collectOutputFieldsFromSdkSpec(collected, view.raw.sdkSpec);
  if (collected.length === 0) {
    for (const field of view.raw.fields || []) {
      collectField(collected, field);
    }
  }
  const items = uniqueBy(
    collected
      .filter((field) => field?.name && fieldNameFor(field, contract))
      .map((field) => ({ raw: field, key: fieldKey(field), name: '' })),
    (field) => field.key,
  );
  assignUniqueNames(items, (field) =>
    camelCase(field.raw.label || field.raw.name || 'field'),
  );
  return items;
}

function collectOutputFieldsFromSdkSpec(fields, sdkSpec) {
  const spec = sdkSpec?.spec;
  if (!spec || typeof spec !== 'object') {
    return;
  }
  const builder = builderMethod(sdkSpec.builder);
  if (builder === 'records') {
    for (const field of spec.fields || []) collectField(fields, field);
    return;
  }
  if (builder === 'sql') {
    for (const field of spec.fields || []) collectField(fields, field);
    return;
  }
  if (builder === 'analysis' || builder === 'metric') {
    collectField(fields, spec.primaryMeasure);
    for (const measure of spec.measures || []) collectField(fields, measure);
    for (const dimension of spec.dimensions || []) collectField(fields, dimension);
    collectField(fields, spec.dateField);
    return;
  }
  if (builder === 'matrix') {
    const rows = matrixAxisLevels(spec.rows);
    const columns = matrixAxisLevels(spec.columns);
    const values = Array.isArray(spec.values) ? spec.values : [];
    for (const row of rows) collectMatrixAxisField(fields, row);
    for (const column of columns) collectMatrixAxisField(fields, column);
    for (const value of values) {
      collectField(fields, value.field);
      collectField(fields, value.measure);
    }
  }
}

function matrixAxisLevels(axis) {
  if (Array.isArray(axis)) {
    return axis;
  }
  if (Array.isArray(axis?.levels)) {
    return axis.levels;
  }
  return [];
}

function collectMatrixAxisField(fields, level) {
  if (looksLikeFieldRef(level)) {
    collectField(fields, level);
    return;
  }
  collectField(fields, level?.field);
}

function isPresentationView(view) {
  return (
    view?.computation?.kind === 'presentation_only' ||
    view?.visual === 'text_block' ||
    view?.visualSpec?.visualType === 'text_block'
  );
}

function compactPresentationView(view) {
  return removeUndefined({
    id: view.id,
    title: view.title,
    purpose: view.purpose,
    visual: view.visual,
    visualSpec: view.visualSpec,
    computation: view.computation,
    uxExpectations: view.uxExpectations,
    validation: view.validation,
    sourceViewIds: view.sourceViewIds,
    content: view.content,
    description: view.description,
  });
}

function collectField(fields, field) {
  if (!field?.name) {
    return;
  }
  fields.push(compactField(field));
}

function compactField(field) {
  return {
    name: field.name,
    label: field.label,
    role: field.role,
    dataType: field.dataType,
    aggregate: field.aggregate,
    sourceKey: field.sourceKey || (field.source ? sourceKey(field.source) : undefined),
  };
}

function looksLikeFieldRef(value) {
  return Boolean(
    value &&
      typeof value === 'object' &&
      typeof value.name === 'string' &&
      (typeof value.role === 'string' ||
        typeof value.dataType === 'string' ||
        typeof value.aggregate === 'string' ||
        value.source ||
        value.sourceKey),
  );
}

function looksLikeSourceRef(value) {
  return Boolean(
    value &&
      typeof value === 'object' &&
      (value.sourceKey ||
        value.kind === 'semantic' ||
        (typeof value.datasetName === 'string' && typeof value.domainId === 'string')),
  );
}

function renderValue(value, contract) {
  if (value === undefined) {
    return 'undefined';
  }
  if (value === null || typeof value === 'number' || typeof value === 'boolean') {
    return JSON.stringify(value);
  }
  if (typeof value === 'string') {
    return JSON.stringify(value);
  }
  if (Array.isArray(value)) {
    return `[${value.map((item) => renderValue(item, contract)).join(', ')}]`;
  }
  if (looksLikeFieldRef(value)) {
    const fieldName = fieldNameFor(compactField(value), contract);
    if (fieldName) return `fields.${fieldName}`;
  }
  if (looksLikeSourceRef(value)) {
    const sourceName = sourceNameFor(value, contract);
    if (sourceName) return `sources.${sourceName}`;
  }
  const entries = Object.entries(value)
    .filter(([, item]) => item !== undefined)
    .map(([key, item]) => `${JSON.stringify(key)}: ${renderValue(item, contract)}`);
  return `{ ${entries.join(', ')} }`;
}

function renderPlainObject(value) {
  return JSON.stringify(value, null, 2);
}

function fieldNameFor(field, contract) {
  if (!field?.name) {
    return undefined;
  }
  return contract.fieldNameByKey.get(fieldKey(compactField(field)));
}

function sourceNameFor(source, contract) {
  if (!source) {
    return undefined;
  }
  return contract.sourceNameByKey.get(source.sourceKey || sourceKey(source));
}

function fieldKey(field) {
  return [
    field.sourceKey || '',
    field.name || '',
    field.role || '',
    field.aggregate || '',
  ].join('|');
}

function fieldRefsReferToSameField(left, right) {
  if (!left || !right || left.name !== right.name) {
    return false;
  }
  return sourceKeyForField(left) === sourceKeyForField(right);
}

function isIdentifierFieldRef(field) {
  return field?.role === 'id';
}

function sourceKey(source) {
  if (!source) {
    return '';
  }
  if (source.sourceKey) {
    return source.sourceKey;
  }
  if (source.kind === 'semantic' || source.datasetName) {
    return ['semantic', source.domainId || '', source.datasetId || source.datasetName || ''].join(':');
  }
  return JSON.stringify(source);
}

function sourceKeyForField(field) {
  return field?.sourceKey || sourceKey(field?.source);
}

function builderMethod(builder) {
  const method = String(builder || '').replace(/^semaphor\./, '');
  if (!['metric', 'records', 'analysis', 'matrix', 'sql'].includes(method)) {
    throw new Error(`Unsupported sdkSpec builder: ${builder}`);
  }
  return method;
}

function isRowShapedBuilder(builder) {
  const method = builderMethod(builder);
  return method === 'records' || method === 'sql';
}

function operatorForInput(input) {
  if (input.operator) return input.operator;
  if (input.type === 'date_range') return 'between';
  if (input.type === 'multi_select' || input.type === 'select') return 'in';
  return '=';
}

function assignUniqueNames(items, suggestedName) {
  const used = new Map();
  for (const item of items) {
    const base = suggestedName(item) || 'item';
    const count = used.get(base) || 0;
    used.set(base, count + 1);
    item.name = count === 0 ? base : `${base}${count + 1}`;
  }
}

function uniqueBy(items, keyFn) {
  const seen = new Set();
  const output = [];
  for (const item of items) {
    const key = keyFn(item);
    if (!key || seen.has(key)) {
      continue;
    }
    seen.add(key);
    output.push(item);
  }
  return output;
}

function camelCase(value) {
  const words = String(value || '')
    .replace(/[^A-Za-z0-9]+/g, ' ')
    .trim()
    .split(/\s+/)
    .filter(Boolean);
  if (words.length === 0) {
    return 'item';
  }
  const [first, ...rest] = words;
  const name = [
    first.toLowerCase(),
    ...rest.map((word) => word.charAt(0).toUpperCase() + word.slice(1).toLowerCase()),
  ].join('');
  return /^[A-Za-z_$]/.test(name) ? name : `item${name}`;
}

function shortSourceName(sourceKeyValue) {
  const parts = String(sourceKeyValue).split(':');
  return parts[parts.length - 1] || sourceKeyValue;
}

function removeUndefined(value) {
  return Object.fromEntries(Object.entries(value).filter(([, item]) => item !== undefined));
}

function booleanArg(value) {
  return value === true || value === 'true' || value === '1' || value === 'yes';
}

function firstString(...values) {
  return values.find((value) => typeof value === 'string' && value.trim()) || '';
}

function writeResult(result) {
  const payload = JSON.stringify(result, null, 2);
  if (args.json || !result.ok) {
    process.stdout.write(`${payload}\n`);
    return;
  }
  process.stdout.write([
    result.ok
      ? 'Semaphor Data App contract generated.'
      : 'Semaphor Data App contract generation failed.',
    payload,
  ].join('\n'));
}
